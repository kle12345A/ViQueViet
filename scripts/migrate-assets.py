def optimize(source: Path, destination: Path, max_width: int) -> None:
    if not source.exists():
        raise FileNotFoundError(source)
    destination.parent.mkdir(parents=True, exist_ok=True)
    with Image.open(source) as image:
        image = ImageOps.exif_transpose(image).convert("RGB")
        if image.width > max_width:
            height = round(image.height * max_width / image.width)
            image = image.resize((max_width, height), Image.Resampling.LANCZOS)
        image.save(destination, "WEBP", quality=82, method=6)


selected: dict[Path, list[str]] = {}

for slug, source in PRODUCTS.items():
    for name, width in (("card.webp", 800), ("hero.webp", 1400)):
        destination = PUBLIC / "images" / "products" / slug / name
        optimize(source, destination, width)
        selected.setdefault(source.resolve(), []).append(destination.relative_to(ROOT).as_posix())

for relative, (source, width) in SUPPORTING.items():
    destination = PUBLIC / "images" / relative
    optimize(source, destination, width)
