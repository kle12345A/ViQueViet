def category_for(path: Path) -> str:
    relative = path.relative_to(SOURCE).as_posix().lower()
    if "ảnh sản phẩm" in relative:
        return "products"
    if "nhà máy" in relative:
        return "factory"
    if "quảng bá" in relative:
        return "news"
    return "other"


